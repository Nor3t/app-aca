"use client";

import Link from "next/link";
import { usePathname } from "next/navigation";

const nav = [
  { href: "/dashboard", label: "Inicio", icon: HomeIcon },
  { href: "/dashboard/comunidad", label: "Comunidad", icon: CommunityIcon },
  { href: "/dashboard/cursos", label: "Curso", icon: CourseIcon },
  { href: "/dashboard/certificado", label: "Cert.", icon: CertIcon },
  { href: "/dashboard/perfil", label: "Perfil", icon: ProfileIcon },
];

export function MobileNav() {
  const pathname = usePathname();

  return (
    <nav className="lg:hidden fixed bottom-0 left-0 right-0 bg-[#0A0A0A]/95 backdrop-blur-xl border-t border-white/5 z-50 px-2 pb-safe">
      <div className="flex items-center justify-around py-2">
        {nav.map(({ href, label, icon: Icon }) => {
          const active = pathname === href || (href !== "/dashboard" && pathname.startsWith(href));
          return (
            <Link key={href} href={href} className="flex flex-col items-center gap-1 px-3 py-2 rounded-xl">
              <Icon className={`w-5 h-5 transition-colors ${active ? "text-red-500" : "text-gray-600"}`} />
              <span className={`text-[10px] font-medium transition-colors ${active ? "text-red-500" : "text-gray-600"}`}>
                {label}
              </span>
            </Link>
          );
        })}
      </div>
    </nav>
  );
}

